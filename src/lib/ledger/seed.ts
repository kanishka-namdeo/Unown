/**
 * The 90-day series, generated by a fixed sinusoid + a fixed weekly
 * rhythm + three fixed spikes (payroll biweekly, a Series A tranche
 * mid-September, an annual software renewal late October). Deterministic
 * by construction — same input digits, same series, every run.
 */
function seriesDay(i: number): FlowDay {
  const d = new Date(Date.UTC(2026, 7, 2 + i));
  const iso = d.toISOString().slice(0, 10);
  const weekday = d.getUTCDay(); // 0 Sun … 6 Sat
  const weekdayFactor = weekday === 0 || weekday === 6 ? 0.25 : 1;
  const wave = Math.sin((i / 90) * Math.PI * 3) * 9_000;
  const drift = i * 140;
  const inflow = Math.round((34_000 + wave + drift) * weekdayFactor);
  const outBase = 27_500 + Math.sin((i / 90) * Math.PI * 2 + 1) * 6_500;
  const outflow = Math.round((outBase + i * 90) * weekdayFactor);
  return { date: iso, inflow, outflow };
}

export const FLOW: FlowDay[] = Array.from({ length: 90 }, (_, i) => {
  const day = seriesDay(i);
  // Fixed spikes — payroll every 14th day, the tranche, the renewal.
  if (i % 14 === 13) day.outflow += 96_400;
  if (day.date === "2026-09-18") day.inflow += 1_250_000;
  if (day.date === "2026-10-27") day.outflow += 88_000;
  return day;
});

