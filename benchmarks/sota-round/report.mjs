#!/usr/bin/env bun
// The SOTA round's report renderer — reads snapshot-*.json files from
// results/ and renders the baseline/midpoint/final comparison as markdown
// with receipts-first sourcing. Every number in the rendered table comes from
// a snapshot JSON; the renderer invents nothing (unmeasured cells print
// "not measured" per the landing figures contract).
//
// Usage:
//   bun report.mjs [baseline mid final ...]   # labels, must match snapshots
//   bun report.mjs                            # renders all, sorted by time
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dir, "results");
const wanted = process.argv.slice(2);
const snaps = readdirSync(dir)
  .filter((f) => f.startsWith("snapshot-") && f.endsWith(".json"))
  .map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")))
  .sort((a, b) => a.takenAt - b.takenAt);
const picked = wanted.length ? snaps.filter((s) => wanted.includes(s.label)) : snaps;
if (picked.length === 0) {
  console.error("no snapshots found");
  process.exit(1);
}
const fmt = (v) => (v === null || v === undefined || v === "" ? "not measured" : String(v));
const row = (name, get) => `| ${name} | ${picked.map((s) => fmt(get(s))).join(" | ")} |`;

let md = `# The SOTA round — benchmark snapshots\n\nGenerated by \`report.mjs\` from \`results/snapshot-*.json\`; collected by \`metrics.mjs\` from the engine DB, the build repo's \`.unown/receipts/\`, and hand-entered phase facts. Nothing here is typed by hand.\n\n`;
md += `| Metric | ${picked.map((s) => s.label).join(" | ")} |\n|---|${picked.map(() => "---").join("|")}|\n`;
md += `| _taken at_ | ${picked.map((s) => s.takenAtIso).join(" | ")} |\n`;
md += `| _phase_ | ${picked.map((s) => fmt(s.phase)).join(" | ")} |\n\n`;
md += `## SDLC metrics\n\n`;
md += row("edit-bench pass rate (harness baseline)", (s) => (s.sdlc.editBench ? `${(s.sdlc.editBench.passRate * 100).toFixed(1)}% (${s.sdlc.editBench.passed}/${s.sdlc.editBench.totalTasks})` : null)) + "\n";
md += row("tests (unit)", (s) => fmt(s.sdlc.tests.unit)) + "\n";
md += row("tests (e2e)", (s) => fmt(s.sdlc.tests.e2e)) + "\n";
md += row("e2e verdict", (s) => fmt(s.sdlc.e2e)) + "\n\n";
md += `## Agent metrics\n\n`;
md += row("build sessions", (s) => s.agent.sessions) + "\n";
md += row("tool calls", (s) => s.agent.toolCalls) + "\n";
md += row("tool success rate", (s) => (s.agent.toolSuccessRate === null ? null : `${(s.agent.toolSuccessRate * 100).toFixed(1)}%`)) + "\n";
md += row("checkpoints", (s) => s.agent.checkpoints) + "\n";
md += row("resume chains", (s) => s.agent.resumeChains) + "\n";
md += row("human interventions", (s) => fmt(s.agent.humanInterventions || null)) + "\n\n";
md += `## Learning metrics (engine DB)\n\n`;
md += row("harness cycles", (s) => s.learning.cyclesTotal) + "\n";
md += row("improvements shipped", (s) => s.learning.improvementsShipped) + "\n";
md += row("tasks (total / minted)", (s) => `${s.learning.tasksTotal} / ${s.learning.tasksMinted}`) + "\n";
md += row("dreams (merged/added/pruned)", (s) => `${s.learning.dreamsMerged}/${s.learning.dreamsAdded}/${s.learning.dreamsPruned}`) + "\n";
md += row("notes", (s) => s.learning.notesTotal) + "\n";
md += row("memory versions", (s) => s.learning.memoryVersions) + "\n";
md += row("skills staged", (s) => s.learning.skillsStaged) + "\n";
md += row("hook decisions", (s) => s.learning.hookDecisions) + "\n";
md += row("failures logged (validation log)", (s) => fmt(s.learning.failuresLogged || null)) + "\n";

const out = join(dir, "REPORT.md");
writeFileSync(out, md);
console.log(`wrote ${out}`);
