/**
 * bwrap.ts — OS-level sandbox for untrusted executions.
 *
 * Defense-in-depth beneath the TypeScript path jail: every command the
 * engine executes inside a sandbox (verify scripts, and — via the generated
 * shell wrapper — every agent bash-tool command) runs under the host's
 * OS sandbox, dispatched per platform:
 *
 *   Linux  -> bubblewrap (bwrap), the historical backend
 *   macOS  -> seatbelt (sandbox-exec), bwrap-equivalent semantics
 *   other  -> none (the TS path jail remains the only barrier)
 *
 * Linux (bubblewrap) profile — unchanged since the original audit:
 *
 *   - whole root filesystem read-only (child mounts /sys stay read-only,
 *     /proc and /dev are replaced with fresh instances)
 *   - /home, /run, /tmp, /var/tmp are private tmpfs — the engine's data,
 *     the repository (incl. .env) and ~/.unown are invisible
 *   - the sandbox workspace is bind-mounted at its REAL path (no path
 *     translation: engine and sandboxed process agree on paths)
 *   - network namespace killed (no egress, no bridge, no DNS)
 *   --unshare-ipc, --new-session, --cap-drop ALL, --die-with-parent
 *
 * macOS (seatbelt) profile — generated by buildSeatbeltProfile as text and
 * fed to sandbox-exec via -f (see that function for the line-by-line
 * bwrap mapping). sandbox-exec is deprecated by Apple but shipped on every
 * macOS and is what shipping agents (Claude Code, Codex) use today. Two
 * documented asymmetries (darwin has no mount namespaces):
 *   - reads: the host filesystem — including $HOME — stays READABLE
 *     (bwrap ro-binds / the same way, but its /home tmpfs hides the host
 *     home; seatbelt cannot hide it, it can only deny writes);
 *   - writes: confined to the workspace, /private/tmp, /var/folders and
 *     /dev/null — the same write-isolation as bwrap's tmpfs mounts, but
 *     the tmp areas are SHARED with the host, not private copies.
 *
 * Selection rationale (researched online, see worklog): bubblewrap is the
 * sandbox foundation of Flatpak (a decade of deployment), and is what both
 * Claude Code (Linux sandboxing) and OpenAI Codex's current Linux sandbox
 * build on; those same products use macOS seatbelt profiles on darwin.
 * Landlock (the Linux alternative) requires kernel >= 5.13 — this host
 * runs 5.10. microVM/gVisor/Kata options need KVM or a container runtime,
 * unavailable here.
 *
 * Known residuals on this kernel (5.10 container): fresh procfs inside a
 * nested pid namespace is refused (EPERM), so there is no --unshare-pid;
 * host pids are listed in /proc but signals to them are refused by user-
 * namespace credentials (verified), and /sys is visible read-only. The
 * workspace bind creates its ancestor directory chain on the /home tmpfs —
 * those directory NAMES are visible, but their contents (repo, .env,
 * engine data) are not. Seatbelt residuals: no namespace isolation at all
 * (mach-lookup must stay allowed for libc bootstrap; signals to other
 * host processes are refused by (deny default) + (allow signal (target
 * self)); there is no die-with-parent / new-session / cap-drop equivalent.
 *
 * Environment knobs:
 *   UNOWN_OS_SANDBOX        0 disables the OS sandbox (default: enabled)
 *   UNOWN_SANDBOX_REQUIRED  1|true fails engine runs when the OS sandbox is
 *                           unavailable instead of degrading to the path jail
 *                           (default: unset — transparent fallback)
 *   UNOWN_SANDBOX_NET       1 keeps the network shared (default: blocked)
 *   UNOWN_BWRAP             explicit path to the bwrap binary (Linux)
 *   UNOWN_SANDBOX_EXEC      explicit path to sandbox-exec (macOS)
 */
import { createHash } from "node:crypto";
import { chmodSync, existsSync, mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

/** Resolve the bwrap binary: env override -> vendored copy -> system PATH.
 *  Linux-only by explicit gate: bubblewrap is a Linux ELF tool, and without
 *  the gate a Git-Bash /usr/bin/bwrap from a WSL mount could win on Windows
 *  by accident. Non-linux hosts always resolve null (-> TS path jail). */
export function resolveBwrapPath(): string | null {
        if (process.platform !== "linux") return null;
        const override = process.env.UNOWN_BWRAP;
        if (override && existsSync(override)) return override;
        const vendored = join(HERE, "..", "native", "bin", "bwrap");
        if (existsSync(vendored)) return vendored;
        for (const p of ["/usr/bin/bwrap", "/usr/local/bin/bwrap"]) {
                if (existsSync(p)) return p;
        }
        return null;
}

/** Resolve the sandbox-exec binary: env override -> /usr/bin/sandbox-exec.
 *  Darwin-only by explicit gate (the mirror of resolveBwrapPath): seatbelt
 *  profiles are a macOS mechanism, and a Git-Bash sandbox-exec from a WSL
 *  mount must never win on other hosts by accident. sandbox-exec ships at
 *  /usr/bin on every macOS (it is deprecated but still present); the
 *  override exists for nonstandard setups. Non-darwin hosts always
 *  resolve null (-> TS path jail). */
export function resolveSandboxExecPath(): string | null {
        if (process.platform !== "darwin") return null;
        const override = process.env.UNOWN_SANDBOX_EXEC;
        if (override && existsSync(override)) return override;
        if (existsSync("/usr/bin/sandbox-exec")) return "/usr/bin/sandbox-exec";
        return null;
}

/** The OS-sandbox backend for this host: "bwrap" on Linux, "seatbelt" on
 *  macOS, null when the platform has no backend or its toolchain is absent
 *  (win32/other -> null -> TS path jail). Pure platform/toolchain dispatch
 *  — the UNOWN_OS_SANDBOX=0 kill-switch is applied by the callers, exactly
 *  as resolveBwrapPath has always done. */
export function resolveOsSandboxBackend(): "bwrap" | "seatbelt" | null {
        if (process.platform === "linux") return resolveBwrapPath() === null ? null : "bwrap";
        if (process.platform === "darwin") return resolveSandboxExecPath() === null ? null : "seatbelt";
        return null;
}

export function osSandboxConfigured(): boolean {
        return process.env.UNOWN_OS_SANDBOX !== "0";
}

export function netBlocked(): boolean {
        return process.env.UNOWN_SANDBOX_NET !== "1";
}

// ---------------------------------------------------------------------------
// UNOWN_SANDBOX_REQUIRED — the fail-closed sandbox knob (SA-B1)
// ---------------------------------------------------------------------------
// The historical contract is OPEN-fallback: a host whose OS sandbox is
// unavailable (missing bwrap binary, failed bwrap/seatbelt smoke probe, no
// backend on native Windows, UNOWN_OS_SANDBOX=0 kill-switch) silently degrades
// engine runs to the in-process TS path jail — auditable after the fact via
// run.sandbox_isolation = 'process' (M6-3) but never refused. Research task
// 2-b P0-7 (worklog): operators who NEED the isolation guarantee (untrusted
// curriculum, hostile-network hosts, compliance) must be able to make the
// degrade IMPOSSIBLE — the Unown equivalent of Claude Code's documented
// sandboxing `failIfUnavailable` contract. That is this knob: armed, the two
// engine-run degrade points (sandbox.ts execInSandbox for verify/exec, and
// runner.ts runAgent for the agent bash-tool shell) throw the typed
// SandboxRequiredError instead of weakening the isolation level.

/** Knob parse (call-time env read, the osSandboxConfigured/netBlocked
 *  convention): "1" or "true" arms the fail-closed behavior; anything else
 *  (unset included) keeps the historical transparent fallback. Only the two
 *  exact strings — same strictness the other knobs pin as QUIRKs. */
export function sandboxRequired(): boolean {
        const v = process.env.UNOWN_SANDBOX_REQUIRED;
        return v === "1" || v === "true";
}

/** PURE decision for the knob: what an engine run does when the OS sandbox is
 *  NOT available on this host — "degrade" (default: the documented
 *  transparent path-jail fallback) or "fail" (knob armed: typed error, no
 *  silent weakening). Both arguments explicit so the decision table is
 *  unit-testable without env plumbing; callers pass the probed availability
 *  and take the `required` default from the env at call time. */
export function decideSandboxFallback(available: boolean, required: boolean = sandboxRequired()): "degrade" | "fail" {
        return !available && required ? "fail" : "degrade";
}

/** The actionable message SandboxRequiredError carries — names the backend
 *  this platform was expected to provide (and the kill-switch clash when
 *  UNOWN_OS_SANDBOX=0 is what disabled it) so the operator knows exactly what
 *  to fix. Windows gets the documented story: kernel-grade isolation is not
 *  available on native Windows — use WSL2 or unset the knob. */
export function sandboxRequiredMessage(): string {
        const expected =
                process.platform === "darwin"
                        ? "seatbelt (sandbox-exec at /usr/bin/sandbox-exec)"
                        : process.platform === "win32"
                                ? "none — kernel-grade isolation is not available on native Windows; use WSL2 or unset the knob"
                                : "bubblewrap (vendored native/bin/bwrap, system bwrap, or UNOWN_BWRAP)";
        const clash = osSandboxConfigured()
                ? ""
                : " — note UNOWN_OS_SANDBOX=0 is set: that kill-switch disables the very sandbox this knob requires";
        return `UNOWN_SANDBOX_REQUIRED is set but the OS sandbox is unavailable on this host (expected here: ${expected})${clash}. Refusing to degrade engine runs to the TypeScript path jail — repair the sandbox backend or unset UNOWN_SANDBOX_REQUIRED to re-enable the documented path-jail fallback.`;
}

/** Typed failure thrown by the engine-run degrade points when the knob is
 *  armed (see the knob block above). Same pattern as GhUnavailableError
 *  (pr-review.ts): actionable message, stable name — runAgent's catch
 *  finalizes it as a status:'error' run row and the router's job error path
 *  records it, so the refusal is loud, typed and auditable. */
export class SandboxRequiredError extends Error {
        constructor(message: string = sandboxRequiredMessage()) {
                super(message);
                this.name = "SandboxRequiredError";
        }
}

/** The validated bubblewrap profile (see scripts/bwrap_smoke.sh evidence). */
export function bwrapArgs(workspace: string, net = netBlocked(), execPath: string = process.execPath): string[] {
        const args: string[] = [
                "--ro-bind",
                "/",
                "/",
                "--proc",
                "/proc",
                "--dev",
                "/dev",
                "--tmpfs",
                "/home",
                "--tmpfs",
                "/run",
                "--tmpfs",
                "/tmp",
                "--tmpfs",
                "/var/tmp",
                "--bind",
                workspace,
                workspace,
                "--chdir",
                workspace,
                "--die-with-parent",
                "--new-session",
                "--cap-drop",
                "ALL",
                "--setenv",
                "HOME",
                "/tmp/home",
                "--setenv",
                "TMPDIR",
                "/tmp",
        ];
        // The default bun install (~/.bun/bin) sits under /home — which the
        // --tmpfs /home above masks inside the sandbox. Without this bind every
        // sandboxed `bun run …` (engine verify scripts, harness runs) fails
        // with "bun: command not found" on hosts where bun lives under a
        // masked tree (the bun.sh installer default, GitHub Actions runners).
        // Ordered AFTER the tmpfs mounts so the later mount wins.
        for (const bind of runtimeBindArgs(execPath)) args.push(...bind);
        if (net) args.push("--unshare-net", "--unshare-ipc");
        return args;
}

/** Extra --ro-bind flags that make the bun runtime visible inside the
 *  sandbox when its executable directory sits under a tmpfs-masked tree
 *  (/home, /run, /tmp, /var/tmp). Linux-only (the bwrap backend itself is
 *  linux-gated); empty on system installs (/usr/local/bin, /opt/…). The
 *  exec dir is realpath'd so a ~/.bun symlink farm cannot dodge the check. */
export function runtimeBindArgs(execPath: string): string[][] {
        if (process.platform !== "linux" || !execPath) return [];
        let dir: string;
        try {
                dir = dirname(realpathSync(execPath));
        } catch {
                dir = dirname(execPath);
        }
        const masked = ["/home", "/run", "/tmp", "/var/tmp"];
        if (!masked.some((m) => dir === m || dir.startsWith(`${m}/`))) return [];
        return [["--ro-bind", dir, dir]];
}

