/**
 * bwrap.ts — OS-level sandbox for untrusted executions.
 *
 * Defense-in-depth beneath the TypeScript path jail: every command the
 * engine executes inside a sandbox (verify scripts, and — via the generated
 * shell wrapper — every agent bash-tool command) runs under the host's
 * OS sandbox, dispatched per platform:
 *
 *   Linux  -> bubblewrap (bwrap), the historical backend
 *   macOS  -> seatbelt (sandbox-exec), bwrap-equivalent semantics
 *   other  -> none (the TS path jail remains the only barrier)
 *
 * Linux (bubblewrap) profile — unchanged since the original audit:
 *
 *   - whole root filesystem read-only (child mounts /sys stay read-only,
 *     /proc and /dev are replaced with fresh instances)
 *   - /home, /run, /tmp, /var/tmp are private tmpfs — the engine's data,
 *     the repository (incl. .env) and ~/.unown are invisible
 *   - the sandbox workspace is bind-mounted at its REAL path (no path
 *     translation: engine and sandboxed process agree on paths)
 *   - network namespace killed (no egress, no bridge, no DNS)
 *   --unshare-ipc, --new-session, --cap-drop ALL, --die-with-parent
 *
 * macOS (seatbelt) profile — generated by buildSeatbeltProfile as text and
 * fed to sandbox-exec via -f (see that function for the line-by-line
 * bwrap mapping). sandbox-exec is deprecated by Apple but shipped on every
 * macOS and is what shipping agents (Claude Code, Codex) use today. Two
 * documented asymmetries (darwin has no mount namespaces):
 *   - reads: the host filesystem — including $HOME — stays READABLE
 *     (bwrap ro-binds / the same way, but its /home tmpfs hides the host
 *     home; seatbelt cannot hide it, it can only deny writes);
 *   - writes: confined to the workspace, /private/tmp, /var/folders and
 *     /dev/null — the same write-isolation as bwrap's tmpfs mounts, but
 *     the tmp areas are SHARED with the host, not private copies.
 *
 * Selection rationale (researched online, see worklog): bubblewrap is the
 * sandbox foundation of Flatpak (a decade of deployment), and is what both
 * Claude Code (Linux sandboxing) and OpenAI Codex's current Linux sandbox
 * build on; those same products use macOS seatbelt profiles on darwin.
 * Landlock (the Linux alternative) requires kernel >= 5.13 — this host
 * runs 5.10. microVM/gVisor/Kata options need KVM or a container runtime,
 * unavailable here.
 *
 * Known residuals on this kernel (5.10 container): fresh procfs inside a
 * nested pid namespace is refused (EPERM), so there is no --unshare-pid;
 * host pids are listed in /proc but signals to them are refused by user-
 * namespace credentials (verified), and /sys is visible read-only. The
 * workspace bind creates its ancestor directory chain on the /home tmpfs —
 * those directory NAMES are visible, but their contents (repo, .env,
 * engine data) are not. Seatbelt residuals: no namespace isolation at all
 * (mach-lookup must stay allowed for libc bootstrap; signals to other
 * host processes are refused by (deny default) + (allow signal (target
 * self)); there is no die-with-parent / new-session / cap-drop equivalent.
 *
 * Environment knobs:
 *   UNOWN_OS_SANDBOX     0 disables the OS sandbox (default: enabled)
 *   UNOWN_SANDBOX_NET    1 keeps the network shared (default: blocked)
 *   UNOWN_BWRAP          explicit path to the bwrap binary (Linux)
 *   UNOWN_SANDBOX_EXEC   explicit path to sandbox-exec (macOS)
 */
import { createHash } from "node:crypto";
import { chmodSync, existsSync, mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

/** Resolve the bwrap binary: env override -> vendored copy -> system PATH.
 *  Linux-only by explicit gate: bubblewrap is a Linux ELF tool, and without
 *  the gate a Git-Bash /usr/bin/bwrap from a WSL mount could win on Windows
 *  by accident. Non-linux hosts always resolve null (-> TS path jail). */
export function resolveBwrapPath(): string | null {
	if (process.platform !== "linux") return null;
	const override = process.env.UNOWN_BWRAP;
	if (override && existsSync(override)) return override;
	const vendored = join(HERE, "..", "native", "bin", "bwrap");
	if (existsSync(vendored)) return vendored;
	for (const p of ["/usr/bin/bwrap", "/usr/local/bin/bwrap"]) {
		if (existsSync(p)) return p;
	}
	return null;
}

/** Resolve the sandbox-exec binary: env override -> /usr/bin/sandbox-exec.
 *  Darwin-only by explicit gate (the mirror of resolveBwrapPath): seatbelt
 *  profiles are a macOS mechanism, and a Git-Bash sandbox-exec from a WSL
 *  mount must never win on other hosts by accident. sandbox-exec ships at
 *  /usr/bin on every macOS (it is deprecated but still present); the
 *  override exists for nonstandard setups. Non-darwin hosts always
 *  resolve null (-> TS path jail). */
export function resolveSandboxExecPath(): string | null {
	if (process.platform !== "darwin") return null;
	const override = process.env.UNOWN_SANDBOX_EXEC;
	if (override && existsSync(override)) return override;
	if (existsSync("/usr/bin/sandbox-exec")) return "/usr/bin/sandbox-exec";
	return null;
}

/** The OS-sandbox backend for this host: "bwrap" on Linux, "seatbelt" on
 *  macOS, null when the platform has no backend or its toolchain is absent
 *  (win32/other -> null -> TS path jail). Pure platform/toolchain dispatch
 *  — the UNOWN_OS_SANDBOX=0 kill-switch is applied by the callers, exactly
 *  as resolveBwrapPath has always done. */
export function resolveOsSandboxBackend(): "bwrap" | "seatbelt" | null {
	if (process.platform === "linux") return resolveBwrapPath() === null ? null : "bwrap";
	if (process.platform === "darwin") return resolveSandboxExecPath() === null ? null : "seatbelt";
	return null;
}

export function osSandboxConfigured(): boolean {
	return process.env.UNOWN_OS_SANDBOX !== "0";
}

export function netBlocked(): boolean {
	return process.env.UNOWN_SANDBOX_NET !== "1";
}

/** The validated bubblewrap profile (see scripts/bwrap_smoke.sh evidence). */
export function bwrapArgs(workspace: string, net = netBlocked()): string[] {
	const args: string[] = [
		"--ro-bind",
		"/",
		"/",
		"--proc",
		"/proc",
		"--dev",
		"/dev",
		"--tmpfs",
		"/home",
		"--tmpfs",
		"/run",
		"--tmpfs",
		"/tmp",
		"--tmpfs",
		"/var/tmp",
		"--bind",
		workspace,
		workspace,
		"--chdir",
		workspace,
		"--die-with-parent",
		"--new-session",
		"--cap-drop",
		"ALL",
		"--setenv",
		"HOME",
		"/tmp/home",
		"--setenv",
		"TMPDIR",
		"/tmp",
	];
	if (net) args.push("--unshare-net", "--unshare-ipc");
	return args;
}

// ---------------------------------------------------------------------------
// macOS seatbelt (sandbox-exec) backend
// ---------------------------------------------------------------------------

/** The workspace path as the sandbox will see it: physical (symlinks
 *  resolved — on darwin that also maps /tmp -> /private/tmp and /var ->
 *  /private/var, which is what sandbox-exec matches subpaths against).
 *  Falls back to resolve() when the path does not exist yet (callers
 *  create the workspace before wrapping, but probing must not throw). */
export function seatbeltWorkspacePath(workspace: string): string {
	try {
		return realpathSync(workspace);
	} catch {
		return resolve(workspace);
	}
}

/** Escape a path for a seatbelt string literal: \ and " (subpath "..."). */
function escapeSeatbeltPath(p: string): string {
	return p.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

/**
 * Generate the seatbelt profile with bwrap-equivalent semantics — pure
 * text, deterministic, no filesystem access (golden-tested in
 * test/seatbelt.test.ts). Line-by-line bwrap mapping:
 *
 *   (deny default)                      everything not explicitly allowed
 *                                      is refused (bwrap: namespaces +
 *                                      cap-drop; here: syscall-level deny)
 *   (allow file-read*)                  ro root filesystem (bwrap:
 *                                      --ro-bind /). ASYMMETRY: the host
 *                                      $HOME stays readable — bwrap's
 *                                      /home tmpfs hides it; seatbelt
 *                                      cannot hide, only deny writes.
 *   (allow process-exec*)               execute anything on the ro fs
 *   (allow process-fork)                spawn children (bwrap: unrestricted)
 *   (allow sysctl*)                     bwrap: /sys visible read-only
 *   (allow mach-lookup)                 darwin IPC (no --unshare-ipc
 *                                      equivalent; libc bootstrap needs it)
 *   (allow signal (target self))        self-signals only — signals to
 *                                      other host processes stay denied
 *                                      (bwrap: refused by namespace creds)
 *   (allow file-write* /dev/null)       bwrap parity: a fresh /dev inside
 *                                      bwrap has writable device nodes, so
 *                                      `> /dev/null` redirects must work
 *   (allow file-write* /private/tmp)    writable tmp (bwrap: private tmpfs
 *   (allow file-write* /var/folders)    on /tmp /var/tmp — ASYMMETRY: the
 *                                      darwin tmp dirs are SHARED with the
 *                                      host, not private copies; writes are
 *                                      still confined to them). os.tmpdir()
 *                                      on darwin lives under /var/folders;
 *                                      /tmp is /private/tmp (sandbox-exec
 *                                      resolves the symlink).
 *   (allow file-write* <workspace>)     workspace rw at its REAL path — the
 *                                      same no-path-translation rule as the
 *                                      bwrap bind.
 *   (deny file-write* /System)          belt-and-braces (deny default
 *                                      already covers it).
 *   (deny network*)/(allow network*)    matches bwrap --unshare-net: denied
 *                                      unless UNOWN_SANDBOX_NET=1.
 *
 * The workspace argument is embedded VERBATIM (after escaping " and \) —
 * callers pass the physical path from seatbeltWorkspacePath; resolution
 * stays out so this function remains pure and golden-testable.
 */
export function buildSeatbeltProfile(workspace: string, opts: { net: boolean }): string {
	const ws = escapeSeatbeltPath(workspace);
	const netLine = opts.net ? "(allow network*)" : "(deny network*)";
	return [
		"(version 1)",
		"(deny default)",
		"(allow file-read*)",
		"(allow process-exec*)",
		"(allow process-fork)",
		"(allow sysctl*)",
		"(allow mach-lookup)",
		"(allow signal (target self))",
		'(allow file-write* (literal "/dev/null"))',
		'(allow file-write* (subpath "/private/tmp"))',
		'(allow file-write* (subpath "/var/folders"))',
		`(allow file-write* (subpath "${ws}"))`,
		'(deny file-write* (subpath "/System"))',
		netLine,
		"",
	].join("\n");
}

/**
 * Deterministic seatbelt profile location: <os.tmpdir()>/unown-seatbelt-<hash>.sb
 * where hash = first 16 hex chars of sha256 of the PHYSICAL workspace path —
 * one stable file per workspace, regenerated (by ensureSeatbeltProfile) when
 * the workspace or the net flag changes. The generated shell wrapper derives
 * the SAME path with ${TMPDIR:-/tmp}/unown-seatbelt-$(shasum -a 256 ... |
 * cut -c 1-16).sb — on every stock macOS (launchd sets TMPDIR) both
 * spellings are identical; if TMPDIR is unset the two sides simply keep
 * their own (equally valid) copy.
 */
export function seatbeltProfilePath(workspace: string): string {
	const ws = seatbeltWorkspacePath(workspace);
	const hash = createHash("sha256").update(ws).digest("hex").slice(0, 16);
	return join(tmpdir(), `unown-seatbelt-${hash}.sb`);
}

/** Single-entry cache for the generated profile: rewrite only when the
 *  content (workspace + net flag) changes or the file vanished. */
let seatbeltProfileCache: { path: string; content: string } | null = null;

/** Materialize the seatbelt profile for a workspace and return its path. */
function ensureSeatbeltProfile(workspace: string): string {
	const ws = seatbeltWorkspacePath(workspace);
	const content = buildSeatbeltProfile(ws, { net: !netBlocked() });
	const path = seatbeltProfilePath(ws);
	if (
		seatbeltProfileCache &&
		seatbeltProfileCache.path === path &&
		seatbeltProfileCache.content === content &&
		existsSync(path)
	) {
		return path;
	}
	writeFileSync(path, content, "utf8");
	seatbeltProfileCache = { path, content };
	return path;
}

/** Wrap a command argv with the OS-sandbox profile for this host; null when
 *  unavailable. The Linux argv is byte-identical to the historical bwrap
 *  one; seatbelt wraps as [sandbox-exec, -f, <profile>, --, command...]. */
export function wrapCommand(command: string[], workspace: string): string[] | null {
	if (!osSandboxConfigured()) return null;
	const backend = resolveOsSandboxBackend();
	if (backend === "bwrap") {
		const bin = resolveBwrapPath();
		if (!bin) return null;
		return [bin, ...bwrapArgs(workspace), "--", ...command];
	}
	if (backend === "seatbelt") {
		const bin = resolveSandboxExecPath();
		if (!bin) return null;
		return [bin, "-f", ensureSeatbeltProfile(workspace), "--", ...command];
	}
	return null;
}

let availabilityCache: boolean | null = null;

/** One-time bwrap smoke test: can the profile actually execute a command
 *  here? (probe body of osSandboxAvailable, Linux backend) */
async function probeBwrap(bin: string): Promise<boolean> {
	let probeDir: string | null = null;
	try {
		probeDir = mkdtempSync(join(tmpdir(), "unown-bwrap-probe-"));
		const proc = Bun.spawn([bin, ...bwrapArgs(probeDir), "--", "/bin/sh", "-c", "exit 0"], {
			cwd: probeDir,
			stdout: "ignore",
			stderr: "pipe",
		});
		const timer = setTimeout(() => proc.kill(9), 10_000);
		const code = await proc.exited;
		clearTimeout(timer);
		return code === 0;
	} catch {
		return false;
	} finally {
		if (probeDir) {
			try {
				rmSync(probeDir, { recursive: true, force: true });
			} catch {
				/* ignore */
			}
		}
	}
}

/** One-time seatbelt smoke test: can sandbox-exec execute a trivial
 *  profile here? (probe body of osSandboxAvailable, macOS backend) */
async function probeSeatbelt(bin: string): Promise<boolean> {
	try {
		const proc = Bun.spawn([bin, "-p", "(version 1)(allow default)", "--", "/bin/sh", "-c", "exit 0"], {
			stdout: "ignore",
			stderr: "pipe",
		});
		const timer = setTimeout(() => proc.kill(9), 10_000);
		const code = await proc.exited;
		clearTimeout(timer);
		return code === 0;
	} catch {
		return false;
	}
}

/** One-time cached smoke test per backend: can the host's OS sandbox
 *  actually execute a command here? Null backend (win32/other) and the
 *  UNOWN_OS_SANDBOX=0 kill-switch short-circuit to false — the TS path
 *  jail remains the only barrier. */
export async function osSandboxAvailable(): Promise<boolean> {
	if (!osSandboxConfigured()) return false;
	if (availabilityCache !== null) return availabilityCache;
	const backend = resolveOsSandboxBackend();
	let ok = false;
	if (backend === "bwrap") {
		const bin = resolveBwrapPath();
		if (bin) ok = await probeBwrap(bin);
	} else if (backend === "seatbelt") {
		const bin = resolveSandboxExecPath();
		if (bin) ok = await probeSeatbelt(bin);
	}
	availabilityCache = ok;
	return availabilityCache;
}

/** The Linux (bwrap) wrapper script — byte-identical to the historical one. */
function bwrapShellScript(bin: string): string {
	const netArgs = netBlocked() ? "--unshare-net \\\n  --unshare-ipc \\\n  " : "";
	return `#!/bin/sh
# Generated by unown (src/bwrap.ts) — sandbox shell for agent bash commands.
# Invoked as: unown-sandbox-shell -c "<command>"; cwd = sandbox workspace.
# Re-executes the command under bubblewrap with the validated profile.
WS=$(pwd -P)
exec '${bin}' \\
  --ro-bind / / \\
  --proc /proc \\
  --dev /dev \\
  --tmpfs /home \\
  --tmpfs /run \\
  --tmpfs /tmp \\
  --tmpfs /var/tmp \\
  --bind "$WS" "$WS" \\
  --chdir "$WS" \\
  ${netArgs}--die-with-parent \\
  --new-session \\
  --cap-drop ALL \\
  --setenv HOME /tmp/home \\
  --setenv TMPDIR /tmp \\
  -- /bin/bash "$@"
`;
}

/**
 * The macOS (seatbelt) wrapper script. Mirrors the bwrap wrapper: the
 * workspace (WS) is derived from the invocation cwd at RUNTIME, so one
 * generated wrapper serves every session. The deterministic seatbelt
 * profile for that workspace is (re)generated under ${TMPDIR:-/tmp} —
 * the same path convention as the engine side — and the command re-execs
 * under sandbox-exec. The profile text comes from buildSeatbeltProfile
 * with the literal $WSE sentinel: the heredoc expands it at runtime, so
 * the generated file embeds the exact same profile the engine side
 * writes for the same workspace.
 */
function seatbeltShellScript(bin: string): string {
	// strip the single trailing \n so the heredoc writes the profile
	// BYTE-identical to the engine-side file (no extra blank line before EOF).
	const profileBody = buildSeatbeltProfile("$WSE", { net: !netBlocked() }).replace(/\n$/, "");
	return `#!/bin/sh
# Generated by unown (src/bwrap.ts) — sandbox shell for agent bash commands (macOS seatbelt).
# Invoked as: unown-sandbox-shell -c "<command>"; cwd = sandbox workspace.
# Mirrors the bwrap wrapper: the workspace is derived from the invocation
# cwd, its deterministic seatbelt profile is (re)generated under
# \${TMPDIR:-/tmp} — the same path convention as the engine side — and
# the command re-execs under sandbox-exec with bwrap-equivalent semantics.
WS=\$(pwd -P)
PROFILE="\${TMPDIR:-/tmp}/unown-seatbelt-\$(printf '%s' "$WS" | shasum -a 256 | cut -c 1-16).sb"
# escape \\ and " so the workspace path stays a valid SBPL string literal
WSE=\$(printf '%s' "$WS" | sed 's/\\\\/\\\\\\\\/g; s/"/\\\\"/g')
cat > "$PROFILE" <<EOF
${profileBody}
EOF
exec '${bin}' -f "$PROFILE" -- /bin/bash "$@"
`;
}

/**
 * Generate the sandbox shell wrapper the pi bash tool will use as its shell
 * (SettingsManager.inMemory({ shellPath })). Invoked as `<wrapper> -c "<cmd>"`
 * with cwd = the sandbox workspace, it re-executes the command under the
 * host's OS sandbox (bubblewrap on Linux, seatbelt on macOS). The workspace
 * is derived from the invocation cwd — no per-run state needed. Hosts with
 * no backend (win32/other) get null and run un-wrapped; the UNOWN_OS_SANDBOX=0
 * kill-switch disables the wrapper everywhere.
 */
export function writeSandboxShell(agentDir: string): string | null {
	if (!osSandboxConfigured()) return null;
	const backend = resolveOsSandboxBackend();
	if (backend === null) return null;
	const bin = backend === "bwrap" ? resolveBwrapPath() : resolveSandboxExecPath();
	if (!bin) return null;
	mkdirSync(agentDir, { recursive: true });
	const shellPath = join(agentDir, "unown-sandbox-shell");
	const script = backend === "bwrap" ? bwrapShellScript(bin) : seatbeltShellScript(bin);
	writeFileSync(shellPath, script, "utf8");
	chmodSync(shellPath, 0o755);
	return shellPath;
}
