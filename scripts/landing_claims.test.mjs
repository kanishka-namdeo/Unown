test("template prefix: the page pins v6 and the gate does NOT cry wolf", () => {
  const src = buildSource(
    "pi-repo/hooks.ts",
    'logHook(runId, "SessionStart", null, "log", `session started (memory v${ctx.memoryVersion})`);',
  );
  const literal = "session started (memory v6)";
  assert.ok(matchLiteral(literal, [src]), "prefix matching must resolve a pinned instance");
  // The point of the rule: whole-rendered-string equality would have failed here.
  assert.ok(!src.compact.includes(literal), "fixture sanity: the source does not contain the rendered literal");
});

test("a literal that exists nowhere produces a failure the reporter can print", () => {
  const src = buildSource("a.ts", 'log(`session started in ${opts.cwd}`); log("totally different");');
  assert.equal(matchLiteral("session ended · note queued → engine", [src]), null);
  assert.ok(matchLiteral("session started in /home/z/proj", [src]), "prefix rule keeps real instances passing");
  const f = {
    page: "src/components/landing/integrity.tsx",
    line: 63,
    literal: "session ended · note queued → engine",
    sources: ["a.ts", "b.ts"],
  };
  assert.match(
    renderFailure(f),
    /^FAIL {2}src\/components\/landing\/integrity\.tsx:63 {2}"session ended · note queued → engine" {2}not found in a\.ts or b\.ts$/,
  );
});

test("curly quotes are display, not claim: they fold against the straight-quote template", () => {
  const src = buildSource("h.ts", 'logHook(`prompt submitted: "${text}"`);');
  assert.ok(matchLiteral('prompt submitted: “why does checkout.spec flake…?”', [src]));
});

test("middle segments resolve lines that sit after an interpolation", () => {
  const src = buildSource(
    "t.ts",
    "`Terminal session${tag} in ${cwd} (${min} min): ${prompts} prompt(s), ${calls} tool call(s)${names}.`",
  );
  assert.ok(matchLiteral("14 tool call(s) (read, grep, edit, bash).", [src]));
});

test("a wrapped tail resolves joined with its head, not on its own", () => {
  // The page hard-wraps one engine log entry across two authored lines; the
  // gate re-checks the tail with the line above it (beats only).
  const harness = buildSource(
    "pi-repo/harness.ts",
    "logCycle(`candidate ${candidate.id.slice(0, 8)} + confirmation both passed — patch shipped to ${tier} memory (v${shippedVersion})`, cycleId);",
  );
  const pages = fixturePages({
    hook: '  ["PreToolUse", "deny", "refusing rm on filesystem root"],\n',
    work: '  "Terminal session in /x (1 min): 2 prompt(s),",\n',
    learn:
      '  "candidate 8f21c0a3 + confirmation both passed — patch shipped",\n' +
      '  "to project memory (v7)",\n',
    commands: '  ["unown setup", "wizard"],\n',
    slash: "<code>/plan</code>",
  });
  const sources = fixtureSources(FULL_HELP);
  sources.harness = harness;
  assert.deepEqual(gate(pages, sources).failures, []);
  // The wrap tail alone is NOT a claim the source answers — only joined with
  // its head does it resolve, which is exactly what beat chaining adds.
  assert.equal(
    matchLiteral("to project memory (v7)", [harness]),
    null,
    "a bare wrap tail must not resolve on its own; chaining is what makes it pass",
  );
});

test("template extraction survives the odd backtick a doc comment leaves behind", () => {
  // hooks.ts-style corpus: comments quote `session_start` in prose, so a naive
  // backtick-pair scan goes out of phase and every template-dependent claim
  // fails. The walker must still find the real template.
  const src = buildSource(
    "h.ts",
    "// SessionStart -> pi `session_start\nconst x = 1; // and `tool_call` here\nlogHook(`session started (memory v${ctx.memoryVersion})`);\n",
  );
  assert.ok(matchLiteral("session started (memory v6)", [src]));
});

