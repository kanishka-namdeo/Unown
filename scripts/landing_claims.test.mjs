test("the CLI checks out loud — a silent --check is a decorative gate", () => {
  const r = spawnSync(process.execPath, [join(ROOT, "scripts", "landing_claims.mjs"), "--check"], {
    encoding: "utf8",
    cwd: ROOT,
  });
  // Deliberately NOT asserting status === 0: the current page's verdict is the
  // script's output, not a fixture. What must hold is that the self-invocation
  // guard fires and a verdict is printed at all.
  assert.ok(r.status === 0 || r.status === 1, `expected a verdict exit, got ${r.status}: ${r.stderr}`);
  assert.match(`${r.stdout}\n${r.stderr}`, /^(?:ok |FAIL |landing_claims:)/m);
});

test("the project-memory route can say no — a dream line not in the file fails", () => {
  // AutoDream rewrites .unown/memory/project.md on a schedule, so the loop
  // section's "verbatim lines" claim is the kind that goes stale with nobody
  // touching the page. This is the check that notices.
  const pages = fixturePages({
    hook: '  ["SessionStart", "log", "session started (memory v6)"],\n',
    work: '  "Terminal session in /x (1 min): 2 prompt(s),",\n',
    learn: '  "baseline passed — no improvement needed",\n',
    dream: '  "- A rule AutoDream never wrote, paraphrased by hand.",\n',
    commands: '  ["unown setup", "wizard"],\n',
    slash: '<code>/plan</code>',
  });
  const { failures } = gate(pages, fixtureSources(FULL_HELP));
  assert.equal(failures.length, 1);
  assert.equal(failures[0].literal, "- A rule AutoDream never wrote, paraphrased by hand.");
  assert.deepEqual(failures[0].sources, [".unown/memory/project.md"]);
});
