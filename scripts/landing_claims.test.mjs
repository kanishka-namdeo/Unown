test("page extractors read the arrays the sections actually author", () => {
  const integrity = [
    "const LOG = [",
    '  ["SessionStart", "log", "session started (memory v6)"],',
    "  [",
    '    "SubagentStop",',
    '    "log",',
    '    "candidate 8f21c0a3 + confirmation both passed — patch shipped to project memory (v7)",',
    "  ],",
    "] as const;",
  ].join("\n");
  const rows = parseHookLog(integrity);
  assert.deepEqual(rows[0], { line: 2, hook: "SessionStart", literal: "session started (memory v6)" });
  assert.equal(rows.length, 2, "a prettier-split entry is a claim too — a dropped row is a silently unchecked one");
  assert.equal(rows[1].hook, "SubagentStop");
  assert.equal(rows[1].literal, "candidate 8f21c0a3 + confirmation both passed — patch shipped to project memory (v7)");

  const loop = [
    "const BEATS: Beat[] = [",
    "  {",
    '    key: "work",',
    "    body: [",
    '      "Terminal session in /x (1 min): 2 prompt(s),",',
    '      "",',
    '      "  ...",',
    '      "Final outcome: green.",',
    '    ].join("\\n"),',
    "  },",
    "];",
  ].join("\n");
  assert.deepEqual(
    parseBeats(loop, "work").map((r) => r.line),
    [5, 8],
    "blank lines and ... pacing are layout, not claims",
  );

  const quickstart = [
    "const COMMANDS: [string, string][] = [",
    '  ["unown setup", "wizard"],',
    "  ['unown \"fix it\"', 'start with a prompt'],",
    "];",
  ].join("\n");
  assert.deepEqual(parseCommands(quickstart).map((r) => r.cmd), ["unown setup", 'unown "fix it"']);
  assert.deepEqual(
    parseSlashCommands('x <code className="c">/plan</code>, y <code>/mcp</code> z <code>todo</code>').map((r) => r.cmd),
    ["/plan", "/mcp"],
  );

  const split = [
    "const COMMANDS: [string, string][] = [",
    '  ["/split", "toggle all panels"],',
    '  ["/split-save", "save the layout"],',
    "];",
  ].join("\n");
  assert.deepEqual(parseSplitCommands(split).map((r) => r.cmd), ["/split", "/split-save"]);
});

test("command claims name the command, not its arguments", () => {
  assert.equal(commandClaim("unown mcp add playwright npx @playwright/mcp@latest"), "unown mcp");
  assert.equal(commandClaim('unown "fix the failing tests"'), "unown");
  assert.equal(commandClaim('unown -p "explain the build error"'), "unown -p");
  assert.equal(commandClaim("unown doctor"), "unown doctor");
});

