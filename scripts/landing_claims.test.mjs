const FAKE_ROUTER = [
  "export interface JobDef { id: string }",
  "export const JOB_DEFS: JobDef[] = [",
  "\t{",
  '\t\tid: "harness-cycle",',
  '\t\tname: "Self-improvement cycle",',
  '\t\tkind: "interval",',
  "\t\tscheduleMs: 10 * 60_000,",
  '\t\tdescription: "Runs the loop (keeps newest 40); trap id: not-a-job",',
  "\t},",
  "\t{",
  '\t\tid: "note-sync",',
  '\t\tkind: "interval",',
  "\t\tscheduleMs: 5 * 60_000,",
  '\t\tdescription: "Ingests notes.",',
  "\t},",
  "\t{",
  '\t\tid: "regression-on-ship",',
  '\t\tkind: "event",',
  '\t\tevent: "improvement:shipped",',
  '\t\tdescription: "Re-runs sampled tasks.",',
  "\t},",
  "];",
].join("\n");

test("a fake JOB_DEFS parses into the job list the page renders, with derived counts", () => {
  const jobs = parseJobDefs(FAKE_ROUTER);
  assert.deepEqual(jobs, [
    { id: "harness-cycle", kind: "interval", interval: "10m", event: null },
    { id: "note-sync", kind: "interval", interval: "5m", event: null },
    { id: "regression-on-ship", kind: "event", interval: null, event: "improvement:shipped" },
  ]);
  assert.deepEqual(buildJobsData(jobs).counts, { total: 3, interval: 2, event: 1 });
});

test("zero jobs is a hard failure, never an empty success", () => {
  assert.throws(
    () => parseJobDefs("export const JOB_DEFS: JobDef[] = [];"),
    /ZERO jobs/,
  );
  assert.throws(
    () => parseJobDefs("const jobs = computeJobs();"),
    /no `export const JOB_DEFS`/,
  );
});

test("a job without an id, or a broken schedule, fails by name", () => {
  // Fields are read at line starts, the style JOB_DEFS is authored in; a
  // malformed or single-line entry is a hard failure, never a silent parse.
  const job = (body) => `export const JOB_DEFS: JobDef[] = [\n\t{\n${body}\n\t},\n];`;
  assert.throws(
    () => parseJobDefs(job('\t\tkind: "interval",\n\t\tscheduleMs: 60_000,')),
    /entry #1 has no id/,
  );
  assert.throws(
    () => parseJobDefs(job('\t\tid: "x",\n\t\tkind: "interval",\n\t\tscheduleMs: cron("10m"),')),
    /"x" has a scheduleMs this extractor cannot read/,
  );
  assert.throws(
    () => parseJobDefs(job('\t\tid: "x",\n\t\tkind: "event",')),
    /event job "x" declares no event name/,
  );
});

test("humanized intervals: whole minutes, seconds, and the ms fallback", () => {
  assert.equal(humanizeMs(10 * 60_000), "10m");
  assert.equal(humanizeMs(5 * 60_000), "5m");
  assert.equal(humanizeMs(90_000), "90s");
  assert.equal(humanizeMs(500), "500ms");
});

test("the emitted data file carries the jobs and the derived counts verbatim", () => {
  const data = buildJobsData(parseJobDefs(FAKE_ROUTER));
  const out = emitData(data);
  assert.match(out, /GENERATED by scripts\/landing_claims\.mjs/);
  assert.match(out, /"id": "harness-cycle"/);
  assert.match(out, /"interval": 2, "event": 1|"interval": 2,\n\s*"event": 1/);
  assert.equal(out, emitData(data), "emitting must be deterministic or --check is a coin flip");
});

