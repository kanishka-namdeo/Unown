function fixturePages({
  hook = "",
  work = "",
  learn = "",
  dream = '"- A rule AutoDream wrote and kept.",\n  ',
  commands = "",
  slash = "",
  split = '  ["/split", "toggle all panels"],\n',
} = {}) {
  return {
    [PAGES.integrity]: `const LOG = [\n${hook}] as const;\n`,
    [PAGES.loop]: `const BEATS = [\n{\nkey: "work",\nbody: [\n${work}].join("\\n"),\n},\n{\nkey: "learn",\nbody: [\n${learn}].join("\\n"),\n},\n{\nkey: "dream",\nbody: [\n${dream}].join("\\n"),\n},\n];\n`,
    [PAGES.hero]: `const COMMANDS: [string, string][] = [\n${commands}];\n${slash}`,
    [PAGES.splitview]: `const COMMANDS: [string, string][] = [\n${split}];\n`,
  };
}

function fixtureSources(cliHelp) {
  return {
    hooks: buildSource("pi-repo/hooks.ts", 'logHook(`session started (memory v${ctx.memoryVersion})`); log("refusing rm on filesystem root");'),
    termhooks: buildSource("pi-repo/termhooks.ts", '`Terminal session${tag} in ${cwd} (${min} min): ${p} prompt(s), ${c} tool call(s)${n}.`'),
    harness: buildSource("pi-repo/harness.ts", 'logCycle(`baseline passed${note} — no improvement needed`, cycleId);'),
    instructionGuard: buildSource("pi-repo/instruction-guard.ts", 'reason: `instruction-set file is not writable in-session: ${match} (${guidance})`'),
    help: buildSource("pi-repo/cli.ts (HELP)", helpBody(`const HELP = \`${cliHelp}\`;\n`)),
    memory: buildSource(
      ".unown/memory/project.md",
      "# Tier 1 — Project Memory\n\n## Known pitfalls\n- A rule AutoDream wrote and kept.\n",
    ),
    splitview: buildSource(
      "pi-repo/packages/self-learning/src/splitview.ts",
      'pi.registerCommand("split", { description: "Toggle all panels" });',
    ),
  };
}

const FULL_HELP = [
  "  unown                    interactive session",
  "  unown setup              provider wizard",
  "  unown changelog [n]      print changelog sections",
  "  unown teleport now       a command the page never shows",
  "  /plan /todos /note /agents /learning /lsp /mcp   session commands",
].join("\n");

test("the gate passes when every quoted literal resolves in its source", () => {
  const pages = fixturePages({
    hook: '  ["SessionStart", "log", "session started (memory v6)"],\n  ["PreToolUse", "deny", "refusing rm on filesystem root"],\n',
    work: '  "Terminal session in /x (1 min): 2 prompt(s),",\n  "3 tool call(s) (read, edit).",\n',
    learn: '  "baseline passed — no improvement needed",\n',
    commands: '  ["unown setup", "wizard"],\n',
    slash: '<code className="c">/plan</code>, <code>/mcp</code>',
  });
  const { failures, checked } = gate(pages, fixtureSources(FULL_HELP));
  assert.deepEqual(failures, []);
  assert.ok(checked >= 6);
});

test("a page literal that exists nowhere fails the gate — the gate can say no", () => {
  const pages = fixturePages({
    hook: '  ["Stop", "log", "session ended · note queued → engine"],\n',
    work: '  "Terminal session in /x (1 min): 2 prompt(s),",\n',
    learn: '  "baseline passed — no improvement needed",\n',
    commands: '  ["unown setup", "wizard"],\n',
    slash: "<code>/plan</code>",
  });
  const { failures } = gate(pages, fixtureSources(FULL_HELP));
  assert.equal(failures.length, 1);
  assert.match(renderFailure(failures[0]), /^FAIL {2}.+integrity\.tsx:2 {2}"session ended · note queued → engine" {2}not found in .+hooks\.ts or .+termhooks\.ts or .+harness\.ts or .+instruction-guard\.ts$/);
});

test("one-directional: HELP is a superset, and an omitted command must NOT fail", () => {
  // FULL_HELP carries /todos /note /agents /learning /lsp and the `changelog`
  // and `teleport` commands; this page claims one command and one slash.
  const pages = fixturePages({
    hook: '  ["PreToolUse", "deny", "refusing rm on filesystem root"],\n',
    work: '  "Terminal session in /x (1 min): 2 prompt(s),",\n',
    learn: '  "baseline passed — no improvement needed",\n',
    commands: '  ["unown setup", "wizard"],\n',
    slash: "<code>/plan</code>",
  });
  const { failures } = gate(pages, fixtureSources(FULL_HELP));
  assert.deepEqual(failures, [], "a completeness check here would fail every commit and get the gate ignored");
});

test("a stale command the page still shows is caught page-side, not excused", () => {
  const pages = fixturePages({
    hook: '  ["PreToolUse", "deny", "refusing rm on filesystem root"],\n',
    work: '  "Terminal session in /x (1 min): 2 prompt(s),",\n',
    learn: '  "baseline passed — no improvement needed",\n',
    commands: '  ["unown dream", "start a dream run"],\n',
    slash: "<code>/plan</code>",
  });
  const { failures } = gate(pages, fixtureSources(FULL_HELP));
  assert.equal(failures.length, 1);
  assert.match(renderFailure(failures[0]), /"unown dream".+not found in .+cli\.ts \(HELP\)$/s);
});

test("split-view rows gate against the registration call, not the bare command word", () => {
  // The page shows "/split"; the extension registers
  // `pi.registerCommand("split", …)`. The gated claim is the registration
  // call itself — "split" appears throughout the module, so matching the
  // bare name would let any mention of the word vouch for the command.
  const src = fixtureSources("").splitview;
  assert.equal(splitCommandClaim("/split"), 'registerCommand("split"');
  assert.ok(matchLiteral(splitCommandClaim("/split"), [src]));
  assert.equal(matchLiteral(splitCommandClaim("/split-magic"), [src]), null);

  const pages = fixturePages({
    hook: '  ["PreToolUse", "deny", "refusing rm on filesystem root"],\n',
    work: '  "Terminal session in /x (1 min): 2 prompt(s),",\n',
    learn: '  "baseline passed — no improvement needed",\n',
    commands: '  ["unown setup", "wizard"],\n',
    slash: "<code>/plan</code>",
    split: '  ["/split-magic", "a command the extension never registered"],\n',
  });
  const { failures } = gate(pages, fixtureSources(FULL_HELP));
  assert.equal(failures.length, 1);
  assert.match(
    renderFailure(failures[0]),
    /"registerCommand\(\"split-magic\"".+not found in .+splitview\.ts$/s,
  );
});

