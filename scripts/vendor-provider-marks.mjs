/**
 * Regenerate `provider-marks.tsx` from Simple Icons.
 *
 *   bun scripts/vendor-provider-marks.mjs
 *
 * Reads each CC0 SVG in `download/providers/`, lifts the `d` attribute, and
 * splices it into the `PROVIDER_MARKS` record. Run this after bumping a pinned
 * Simple Icons version; commit the regenerated component with the change.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = join(process.cwd(), "download", "providers");
const OUT = join(process.cwd(), "src", "components", "landing", "provider-marks.tsx");

/** Display order and the labels we actually show, not the upstream titles. */
const ORDER = [
  "anthropic",
  "openrouter",
  "deepseek",
  "mistralai",
  "alibabacloud",
  "ollama",
  "vllm",
];

const LABEL = {
  anthropic: "Anthropic",
  openrouter: "OpenRouter",
  deepseek: "DeepSeek",
  mistralai: "Mistral AI",
  alibabacloud: "DashScope",
  ollama: "Ollama",
  vllm: "vLLM",
};

const present = new Set(
  readdirSync(SRC)
    .filter((f) => f.endsWith(".svg"))
    .map((f) => f.replace(/\.svg$/, "")),
);

const missing = ORDER.filter((s) => !present.has(s));
if (missing.length) {
  console.error(`missing SVGs in ${SRC}: ${missing.join(", ")}`);
  process.exit(1);
}

const entries = ORDER.map((slug) => {
  const svg = readFileSync(join(SRC, `${slug}.svg`), "utf8");
  const d = svg.match(/ d="([^"]+)"/)?.[1];
  if (!d) {
    console.error(`no d attribute in ${slug}.svg`);
    process.exit(1);
  }
  if (!/viewBox="0 0 24 24"/.test(svg)) {
    console.error(`unexpected viewBox in ${slug}.svg`);
    process.exit(1);
  }
  console.log(`${slug.padEnd(14)} ${d.length} chars`);
  return `  ${slug}: {\n    name: ${JSON.stringify(LABEL[slug])},\n    d:\n      ${JSON.stringify(d)},\n  },`;
});

const template = `/**
 * Provider marks, vendored at build time from Simple Icons.
 *
 * WHY VENDORED AND NOT HOTLINKED
 * Simple Icons' icon files are CC0-1.0 (github.com/simple-icons/simple-icons).
 * Vendoring the path data here means the landing page makes zero third-party
 * requests, cannot 404 because a slug was retired, and renders monochrome in
 * \`currentColor\` so the marks inherit the page's ink colour.
 *
 * WHY OPENAI AND DASHSCOPE ARE THE ONLY TEXT TILES
 * CC0 covers Simple Icons' *files*, not the underlying trademarks — every brand
 * sets its own logo-use guidelines, and nominative use ("works with X") is the
 * only safe framing here. Two gaps we accepted rather than filled badly:
 *   - OpenAI: Simple Icons removed the OpenAI mark in v16 at the brand owner's
 *     request (PR #13944), so shipping the retired path data would mean
 *     deliberately ignoring that request. Text tile instead.
 *   - DashScope: no dedicated slug exists. Alibaba Cloud serves it, and that
 *     mark is the one we use — the tile is labelled for what we talk to.
 *
 * Generated by \`scripts/vendor-provider-marks.mjs\` — do not hand-edit the
 * \`PROVIDER_MARKS\` record. Labels live in that script, marks come from
 * \`https://cdn.jsdelivr.net/npm/simple-icons@v16/icons/<slug>.svg\`.
 */

export type ProviderSlug =
${ORDER.map((s) => `  | "${s}"`).join("\n")};

export const PROVIDER_MARKS: Record<ProviderSlug, { name: string; d: string }> = {
${entries.join("\n")}
};

/** Inline the mark as monochrome SVG so it inherits \`currentColor\`. */
export function ProviderMark({ slug, className }: { slug: ProviderSlug; className?: string }) {
  return (
    <svg viewBox="0 0 24 24" className={className} fill="currentColor" aria-hidden="true">
      <path d={PROVIDER_MARKS[slug].d} />
    </svg>
  );
}
`;

writeFileSync(OUT, template);
console.log(`\nwrote ${OUT}`);