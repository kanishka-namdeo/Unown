/**
 * Ostinato — the K-1 zero-mouse flow lane (ticket O-4, the round's
 * headline: create → review → export → import, keyboard events only,
 * ZERO pointer events anywhere in the spec).
 *
 * THE LAW: no click / mouse / tap calls in THIS file (the O-3
 * (the O-3 hardening row "zero pointer events in the spec", now
 * closed for the create surface). The spec drives the app with
 * ONLY `page.keyboard` presses + the two event-wait lanes
 * (`waitForEvent("download")` / `waitForEvent("filechooser")` —
 * those are event WAYS, not pointer events). The app's OWN
 * internals may synthesize what they need: the export anchor's
 * click call on the export anchor and on the import
 * app.ts, not here (the law binds the spec, not the app).
 *
 * THE PRD HARDENING ROW VERIFIED: "create → review → export →
 * import with keyboard events only; zero pointer events" — the
 * round-trip (export bytes → file → import → storage) closes the
 * data lane end to end: the card the spec created is the card the
 * import puts back.
 *
 * THE FLOW, PINNED STEP BY STEP:
 * 1. EMPTY BOOT: fresh context, NO seed → the honest empty panel
 *    `.ostinato-state` "No decks yet" (P0 #5's never-blank law).
 * 2. CREATE THE DECK VIA THE PALETTE (the enumeration law
 *    exercised): Ctrl+K → `#ostinato-palette` visible → type
 *    "create deck" → the `li[data-cmd="create-deck"]` row
 *    visible → Enter → the palette closes + the create form
 *    opens: `#ostinato-create-form` visible, the dialog role,
 *    and `.ostinato-create-input` `#ostinato-create-name`
 *    FOCUSED (D8's attach-before-focus — the form is in the DOM
 *    before the first field receives focus).
 * 3. Type "E2E flow deck" → Enter (implicit submit from the
 *    single-line input — the native `<form>`'s submit lane) → the
 *    form closes (not visible) → the notice renders:
 *    `.ostinato-notice` contains `Deck "E2E flow deck" created.`
 *    → the empty state flips to "No cards yet" (decks=1, cards=0).
 * 4. CREATE THE CARD VIA THE DIRECT KEY (the hint honesty
 *    exercised — the palette row's kbd hint "C" is the runner
 *    key): press C → the form opens with the card fields → the
 *    deck select `#ostinato-create-deck` shows the one option
 *    "E2E flow deck" (preselected, the chunk-3 D8 preselect
 *    law) → type the front "What flows?" → Tab → focus lands in
 *    `#ostinato-create-back` (the textarea) → type "The
 *    **keyboard**." → Tab → focus lands on the submit button →
 *    Enter → the form closes → `.ostinato-notice` "Card
 *    created." → THE REVIEW SCREEN: `.ostinato-card-front`
 *    contains "What flows?" + `.ostinato-progress` "1 of 1".
 * 5. REVIEW: Space reveal → `.ostinato-card-back` visible + its
 *    `strong` text "keyboard" (the markdown lane) → `3` grade →
 *    the done state `.ostinato-state` "Review complete".
 * 6. EXPORT (the download lane): `waitForEvent("download")` armed
 *    BEFORE Ctrl+E → Ctrl+E → `await dl` → `suggestedFilename()`
 *    === "ostinato-export.json" → `dl.path()` + `fs/promises`
 *    `readFile` → `JSON.parse` → THE STRUCTURE assertions (the
 *    ids are time-generated by `newUniqueId` — NEVER hardcode
 *    them; assert on names/contents + the invariant lane instead):
 *    decks.length === 1, decks[0].name === "E2E flow deck",
 *    cards.length === 1, cards[0].front === "What flows?",
 *    cards[0].back === "The **keyboard**.", cards[0].deckId ===
 *    decks[0].id, decks[0].cardOrder.length === 1 &&
 *    decks[0].cardOrder[0] === cards[0].id (the cardOrder-is-the
 *    card's-id invariant). PLUS the byte-level shape check: the
 *    raw file is CANONICAL COMPACT JSON (toCanonicalJson's
 *    sorted-keys / compact-separators format — the O-2 lane's
 *    byte-stable export), pinned on the serialized key
 *    punctuation: the file contains `"front":"What flows?"`
 *    (no space after the colon; the front/back VALUES contain
 *    spaces, so the colon-spot-check is the honest pin, not a
 *    `not.toContain(": ")` over the whole file).
 * 7. IMPORT (the round-trip): `waitForEvent("filechooser")` armed
 *    BEFORE Ctrl+O → Ctrl+O → `await fc` → `fc.setFiles(path)` →
 *    the app's import path validates + re-renders → the review
 *    screen shows the SAME card again (`.ostinato-card-front`
 *    "What flows?" — the import resets the session, so the
 *    graded card is back in the due queue) → the data round-
 *    tripped through export → file → import → storage.
 * 8. THE ZERO-POINTER RECEIPT: this header swears the law; the
 *    operator gate's grep for click / mouse / tap method calls
 *    file) must return ZERO matches — a spec that violates it
 *    is a red lane by definition.
 *
 * Seeding: NONE — the lane's point is that every piece of data
 * the app holds at export time was created through the keyboard
 * surfaces (the palette + the form), not through a seeded
 * localStorage fixture. The fresh context is the seed.
 *
 * Self-skip: the spec runs under the ostinato config's
 * `OSTINATO_E2E` marker (the Coda `CODA_E2E` precedent); under
 * the root `playwright.config.ts` the marker is unset and the
 * spec self-skips (the landing lane stays untouched).
 *
 * Execution honesty: this spec LANDS COMPLETE but is NOT
 * executed in this build sandbox (Playwright + Chromium are not
 * runnable here). The operator gate re-runs it via `bunx
 * playwright test --config=playwright.ostinato.config.ts` from
 * the repo root. No run is claimed in the receipt that was not
 * performed.
 */
import { readFile } from "node:fs/promises";
import { expect, test, type BrowserContext, type Download, type Page } from "@playwright/test";

test.skip(
  !process.env.OSTINATO_E2E,
  "ostinato lane only — run via playwright.ostinato.config.ts",
);

test.describe.configure({ mode: "serial" });

test("create → review → export → import, keyboard events only, zero pointer events", async ({
  browser,
}) => {
  const ctx: BrowserContext = await browser.newContext();
  const page: Page = await ctx.newPage();

  // ─── 1. EMPTY BOOT: no seed → the honest empty panel ────────
  await page.goto("/");
  await expect(page.locator(".ostinato-state")).toContainText("No decks yet");

  // ─── 2. CREATE THE DECK VIA THE PALETTE ──────────────────────
  // Ctrl+K opens the palette; the input auto-focuses (the P0 #9
  // lane). Type the filter — "create deck" narrows the 17-row
  // enumeration to the create rows (the chunk-2 pin's filter
  // semantics: id/label/group/hint substrings, case-insensitive).
  await page.keyboard.press("Control+k");
  await expect(page.locator("#ostinato-palette")).toBeVisible();
  await expect(page.locator(".ostinato-palette-input")).toBeFocused();
  await page.keyboard.type("create deck");
  await expect(page.locator('#ostinato-palette li[data-cmd="create-deck"]')).toBeVisible();
  // Enter runs the selected command: the palette closes + the
  // create form opens (the chunk-3 dispatch wiring).
  await page.keyboard.press("Enter");
  await expect(page.locator("#ostinato-palette")).not.toBeVisible();
  await expect(page.locator("#ostinato-create-form")).toBeVisible();
  // The dialog role + the attach-before-focus law (D8): the form
  // is in the DOM BEFORE the first field receives focus.
  await expect(page.locator('#ostinato-create-form form[role="dialog"]')).toBeVisible();
  await expect(page.locator("#ostinato-create-name")).toBeFocused();

  // ─── 3. SUBMIT THE DECK (implicit submit from the input) ─────
  // Single-line input: Enter submits the native <form>. Success →
  // the form closes (focus returns to the invoking control) +
  // the notice renders (the D9 surface) + the queue recomputes
  // (the D7 session-restart law).
  await page.keyboard.type("E2E flow deck");
  await page.keyboard.press("Enter");
  await expect(page.locator("#ostinato-create-form")).not.toBeVisible();
  await expect(page.locator(".ostinato-notice")).toContainText(
    'Deck "E2E flow deck" created.',
  );
  // The empty state flips: one deck, zero cards.
  await expect(page.locator(".ostinato-state")).toContainText("No cards yet");

  // ─── 4. CREATE THE CARD VIA THE DIRECT KEY (the hint honesty) ─
  // C is the palette row's kbd hint AND the runner key (the
  // COMMAND_KEY_DISPATCH c/C → create-card mapping). Pressing it
  // on the runner surface is the hint-honesty lane: what the
  // palette row advertises is what the key does.
  await page.keyboard.press("C");
  await expect(page.locator("#ostinato-create-form")).toBeVisible();
  // The deck select shows the one option, preselected (the D8
  // preselect law: selectedIndex = 0 on the first deck).
  await expect(page.locator("#ostinato-create-deck")).toHaveText("E2E flow deck");
  // The preselect law, asserted on the SELECT's own value (an
  // <option> is not an input element — toHaveValue does not apply):
  // the value is the first deck's id, non-empty.
  const deckSelValue = await page.locator("#ostinato-create-deck").inputValue();
  expect(deckSelValue.length).toBeGreaterThan(0);
  // Focus is on the deck select (the D8 first-field law: with
  // decks present, the select is the first field). Tab through:
  // the front input → the back textarea → the submit button.
  await expect(page.locator("#ostinato-create-deck")).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(page.locator("#ostinato-create-front")).toBeFocused();
  await page.keyboard.type("What flows?");
  await page.keyboard.press("Tab");
  await expect(page.locator("#ostinato-create-back")).toBeFocused();
  await page.keyboard.type("The **keyboard**.");
  await page.keyboard.press("Tab");
  await expect(page.locator('#ostinato-create-form button[type="submit"]')).toBeFocused();
  // Enter submits the card: form closes + the notice + the queue
  // recomputes (the new card is due immediately → it is in the
  // queue, the D7 law).
  await page.keyboard.press("Enter");
  await expect(page.locator("#ostinato-create-form")).not.toBeVisible();
  await expect(page.locator(".ostinato-notice")).toContainText("Card created.");
  // THE REVIEW SCREEN: the card's front + the queue progress.
  await expect(page.locator(".ostinato-card-front")).toContainText("What flows?");
  await expect(page.locator(".ostinato-progress")).toContainText("1 of 1");

  // ─── 5. REVIEW: reveal → grade → done ────────────────────────
  await page.keyboard.press(" ");
  await expect(page.locator(".ostinato-card-back")).toBeVisible();
  // The markdown lane: the **keyboard** bold renders as a
  // <strong> inside the back face.
  await expect(page.locator(".ostinato-card-back strong")).toHaveText("keyboard");
  // `3` grade (Good, q=2): the interval advances ≥ 1 day → the
  // card is not due on recompute → the queue empties → the done
  // state renders.
  await page.keyboard.press("3");
  await expect(
    page.locator(".ostinato-state", { hasText: "Review complete" }),
  ).toBeVisible();

  // ─── 6. EXPORT (the download lane — the event wait, not a
  //     pointer event) ──────────────────────────────────────────
  // ARM the wait: create the promise BEFORE the trigger (an await
  // here deadlocks — the event cannot fire before Ctrl+E runs).
  const dl: Promise<Download> = armDownload(page);
  await page.keyboard.press("Control+e");
  const download = await dl;
  // The app's export action sets the download attribute.
  expect(download.suggestedFilename()).toBe("ostinato-export.json");
  // Read the file + assert the STRUCTURE (never the time-generated
  // ids) + the canonical compact shape.
  const path = await download.path();
  expect(path).toBeTruthy();
  const raw = await readFile(path as string, "utf8");
  const parsed = JSON.parse(raw) as {
    decks: { id: string; name: string; cardOrder: string[] }[];
    cards: { id: string; deckId: string; front: string; back: string }[];
  };
  expect(parsed.decks.length).toBe(1);
  expect(parsed.decks[0].name).toBe("E2E flow deck");
  expect(parsed.cards.length).toBe(1);
  expect(parsed.cards[0].front).toBe("What flows?");
  expect(parsed.cards[0].back).toBe("The **keyboard**.");
  // The invariant lane: the card belongs to the deck + the
  // cardOrder array holds the card's id (the deck's cardOrder is
  // the semantic array-of-card-ids order, not re-sorted).
  expect(parsed.cards[0].deckId).toBe(parsed.decks[0].id);
  expect(parsed.decks[0].cardOrder.length).toBe(1);
  expect(parsed.decks[0].cardOrder[0]).toBe(parsed.cards[0].id);
  // The canonical separators pin: the serialized KEY PUNCTUATION
  // has no space after the colon (toCanonicalJson's compact
  // separators). The front value contains spaces, so the honest
  // pin is the colon-spot-check on the serialized key form.
  expect(raw).toContain('"front":"What flows?"');

  // ─── 7. IMPORT (the round-trip — the filechooser event wait) ──
  const fc = page.waitForEvent("filechooser");
  await page.keyboard.press("Control+o");
  const fileChooser = await fc;
  // Set the exported file on the app's synthetic input: the
  // import path validates (io.importData's invariant check) +
  // re-renders (the app's own synthetic-input click + change lane —
  // app code, not spec code).
  await fileChooser.setFiles(path as string);
  // The import resets the session: the graded card (interval ≥
  // 1 day, now re-due from the import's recomputation... honestly:
  // it is NOT due on recompute — but the D1 fallback puts ALL
  // cards in the queue when nothing is due) is back in the
  // review screen. The data round-tripped through
  // export → file → import → storage.
  await expect(page.locator(".ostinato-card-front")).toContainText("What flows?");
  await expect(page.locator(".ostinato-progress")).toContainText("1 of 1");

  await ctx.close();
});

/**
 * Arm a download wait BEFORE the keyboard press that triggers the
 * export. The `waitForEvent` is an event WAIT, not a pointer event
 * (the K-1 law's only sanctioned lanes, alongside the
 * filechooser's `waitForEvent`).
 */
async function armDownload(page: Page): Promise<Download> {
  return page.waitForEvent("download");
}
